"""幸运消费的规则边界与硬门（`exec/26 #66`）。

## 规则出处要分清

| 边界 | 出处 |
|---|---|
| 换算 1 点幸运 = 1 点骰值，线性无折扣 | ✅ 权威表明文（`rules/COC7空白卡CY23Final.xlsx`） |
| 与孤注一掷互斥 | ✅ 权威表明文（单向：push 完的结果不能再花） |
| 只能推成**普通**成功 | ⚠️ 不是独立规则，是那条换算的**推论**——花掉
  (出目−成功率) 点正好把出目降到等于成功率 |
| 理智检定不能花 / 大失败不能补 / 对抗可以花 | ⚠️ 权威表没有，来源是 wiki + 2026-08-02 的用户裁定 |

## 硬门全部是代码，一条都不进 prompt

裁决器对这件事**一个字都不用说**：offer 发不发是纯代码判定，所以这一片能力
的概率面为零（它连 schema 字段都不需要）。
"""

from __future__ import annotations

#: 「差这么多以内才主动问」。
#:
#: 🔴 **它是一个人为切点，不是数据里长出来的边界。** 24 房间 / 93 次检定 /
#: 58 次失败的实测里，失败差距是**连续**的（1,2,3,5,5,6,7,7,9,11,11,13,…），
#: 没有簇也没有谷——08-02 那版"分布是双峰"的说法是小样本的形状，已被推翻。
#: 站得住的理由只剩一条：**经济上花得起**（花费 = 差距，而平均幸运约 50）。
#: 写清楚这点是为了防止后来人以为 10 有实证背书而不敢调它。
#:
#: 实测频率：每次检定约 10% 触发 ⇒ 一局 30 次检定约 3 次。罕见到还是事件，
#: 频繁到有存在感。**放在能力目录里当常量**，不进 `.env`、不做房间选项——
#: 它是规则手感，不是部署配置。
OFFER_GAP_THRESHOLD = 10

#: 能被推成成功的失败等级。**大失败不在内**（规则边界），"成功"类当然也不在。
_PUSHABLE_LEVEL = "失败"


def spend_cost(rolled: int, target: int) -> int:
    """把这次失败推成普通成功要花几点幸运 = 出目 − 成功率。"""
    return rolled - target


def should_offer(*, kind: str, level: str, cost: int, luck_remaining: int) -> bool:
    """要不要**主动**问一句「花幸运吗」。

    🔴 阈值管的是"系统主动打扰你"，不管"你能不能花"——`#66` 的产品判断是
    新手不该被淹没、老手的能力上限也不该被阈值削掉。**主动索取那条路本期没做**
    （理由见 `__init__` 的文档串），所以现在这里就是唯一入口。
    """
    if kind != "skill":
        return False  # SAN 检定整类排除（规则），连 offer 都拿不到
    if level != _PUSHABLE_LEVEL:
        return False  # 大失败不能补，成功不用补
    if cost <= 0:
        return False  # 没有差距可补
    if cost > OFFER_GAP_THRESHOLD:
        return False
    return luck_remaining >= cost
